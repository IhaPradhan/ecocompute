-- EcoCompute relational schema (PostgreSQL)
-- Run this script against the ecocompute database.

CREATE TABLE IF NOT EXISTS clients (
    client_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_name     VARCHAR(100) NOT NULL,
    contact_email   VARCHAR(150) UNIQUE,
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS server_zones (
    zone_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zone_name       VARCHAR(80) NOT NULL UNIQUE,
    location        VARCHAR(120) NOT NULL,
    cooling_type    VARCHAR(60) NOT NULL
);

CREATE TABLE IF NOT EXISTS server_racks (
    rack_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rack_name       VARCHAR(80) NOT NULL UNIQUE,
    zone_id         INTEGER NOT NULL REFERENCES server_zones(zone_id),
    client_id       INTEGER NOT NULL REFERENCES clients(client_id),
    power_draw_kw   NUMERIC(8,2) NOT NULL CHECK (power_draw_kw >= 0),
    installed_on    DATE
);

CREATE TABLE IF NOT EXISTS maintenance_logs (
    log_id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rack_id         INTEGER NOT NULL REFERENCES server_racks(rack_id),
    maintenance_date DATE NOT NULL,
    issue_type      VARCHAR(100) NOT NULL,
    description     TEXT NOT NULL,
    status          VARCHAR(20) NOT NULL DEFAULT 'Open'
                    CHECK (status IN ('Open', 'In Progress', 'Resolved')),
    technician      VARCHAR(100),
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_racks_zone_id
    ON server_racks(zone_id);

CREATE INDEX IF NOT EXISTS idx_logs_rack_date
    ON maintenance_logs(rack_id, maintenance_date DESC);

CREATE INDEX IF NOT EXISTS idx_logs_status
    ON maintenance_logs(status);
